import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { cmdInit, cmdSchemaDiff, parseRenameFlag, type CliIO } from './cli-commands.js';

const INDEX = resolve(import.meta.dirname, 'index.ts');

function schemaSource(userColumn: string): string {
  return `import { defineTable } from '${INDEX}';
import * as v from 'valibot';
export const User = defineTable('User', { ${userColumn}: v.string() });
`;
}

describe('cli commands', () => {
  let cwd: string;
  let errors: string[];
  let logs: string[];
  let asked: string[];
  let answer: boolean;
  let io: CliIO;

  const read = (p: string) => readFileSync(join(cwd, p), 'utf-8');
  const writeSchema = (column: string, file = 'schema.ts') => {
    mkdirSync(join(cwd, 'db'), { recursive: true });
    writeFileSync(join(cwd, 'db', file), schemaSource(column));
  };

  beforeEach(() => {
    cwd = mkdtempSync(join(tmpdir(), 'kyt-pg-cli-'));
    errors = [];
    logs = [];
    asked = [];
    answer = true;
    io = {
      cwd,
      isTTY: false,
      ask: async (q) => {
        asked.push(q);
        return answer;
      },
      log: (l) => logs.push(l),
      error: (l) => errors.push(l),
    };
    mkdirSync(join(cwd, 'db'), { recursive: true });
    writeFileSync(
      join(cwd, 'db/config.ts'),
      `import { defineConfig } from '${INDEX}';\nexport default defineConfig({ migrationsDir: 'db/migrations', namingStrategy: 'sequential' });\n`,
    );
  });

  afterEach(() => {
    rmSync(cwd, { recursive: true, force: true });
  });

  it('init writes config, schema and snapshot, and skips existing files', () => {
    rmSync(join(cwd, 'db'), { recursive: true });
    cmdInit(io, {});
    expect(read('db/config.ts')).toContain("import { defineConfig } from 'kyt-pg';");
    expect(read('db/config.ts')).toContain("migrationsDir: 'db/migrations'");
    expect(JSON.parse(read('db/schema.json'))).toEqual({ version: 1, dialect: 'postgres', tables: {} });
    writeFileSync(join(cwd, 'db/config.ts'), 'custom');
    cmdInit(io, {});
    expect(read('db/config.ts')).toBe('custom');
  });

  it('writes a migration, a snapshot and schema.sql', async () => {
    writeSchema('email');
    expect(await cmdSchemaDiff(io, { name: 'createUser', renames: [], noRename: false })).toBe(0);
    expect(readdirSync(join(cwd, 'db/migrations'))).toEqual(['0001_create_user.sql']);
    expect(read('db/migrations/0001_create_user.sql')).toContain('CREATE TABLE "User"');
    expect(read('db/migrations/0001_create_user.sql')).toContain('-- Generated by kyt-pg schema:diff');
    expect(read('db/schema.sql')).toContain('CREATE TABLE "User"');
    expect(JSON.parse(read('db/schema.json')).dialect).toBe('postgres');
    expect(logs.join('\n')).toContain('Next: review the file, then run your migration job.');
  });

  async function setupV1() {
    writeSchema('name');
    await cmdSchemaDiff(io, { name: 'createUser', renames: [], noRename: false });
    writeSchema('fullName', 'schema2.ts');
  }

  it('stops without a terminal when a rename is possible', async () => {
    await setupV1();
    expect(await cmdSchemaDiff(io, { schema: 'db/schema2.ts', renames: [], noRename: false })).toBe(1);
    expect(errors.join('\n')).toContain('pass --rename <Table>.<old>=<new> for each rename, or pass --no-rename');
    expect(readdirSync(join(cwd, 'db/migrations'))).toEqual(['0001_create_user.sql']);
  });

  it('writes RENAME COLUMN when the user says yes', async () => {
    await setupV1();
    io.isTTY = true;
    expect(await cmdSchemaDiff(io, { name: 'alterUser', schema: 'db/schema2.ts', renames: [], noRename: false })).toBe(0);
    expect(asked).toEqual(['Is column "User"."fullName" a rename of "User"."name"? (y/N)']);
    expect(read('db/migrations/0002_alter_user.sql')).toContain('ALTER TABLE "User" RENAME COLUMN "name" TO "fullName";');
  });

  it('writes RENAME COLUMN from a --rename flag', async () => {
    await setupV1();
    const renames = [parseRenameFlag('User.name=fullName')];
    expect(await cmdSchemaDiff(io, { name: 'alterUser', schema: 'db/schema2.ts', renames, noRename: false })).toBe(0);
    expect(asked).toEqual([]);
    expect(read('db/migrations/0002_alter_user.sql')).toContain('RENAME COLUMN "name" TO "fullName"');
  });

  it('rejects a --rename flag that matches no rename', async () => {
    await setupV1();
    const renames = [parseRenameFlag('User.nmae=fullName')];
    expect(await cmdSchemaDiff(io, { schema: 'db/schema2.ts', renames, noRename: true })).toBe(1);
    expect(errors).toContain(
      'Error: --rename User.nmae=fullName matches no possible rename. Check the names and run schema:diff again.',
    );
    expect(readdirSync(join(cwd, 'db/migrations'))).toEqual(['0001_create_user.sql']);
  });

  it('applies a --rename flag together with --no-rename', async () => {
    await setupV1();
    const renames = [parseRenameFlag('User.name=fullName')];
    expect(await cmdSchemaDiff(io, { name: 'alterUser', schema: 'db/schema2.ts', renames, noRename: true })).toBe(0);
    expect(read('db/migrations/0002_alter_user.sql')).toContain('RENAME COLUMN "name" TO "fullName"');
  });

  it('writes RENAME TO from a table --rename flag', async () => {
    writeSchema('name');
    await cmdSchemaDiff(io, { name: 'createUser', renames: [], noRename: false });
    writeFileSync(join(cwd, 'db/schema2.ts'), schemaSource('name').replace("defineTable('User'", "defineTable('Account'"));
    const renames = [parseRenameFlag('User=Account')];
    expect(await cmdSchemaDiff(io, { name: 'renameUser', schema: 'db/schema2.ts', renames, noRename: false })).toBe(0);
    expect(read('db/migrations/0002_rename_user.sql')).toContain('ALTER TABLE "User" RENAME TO "Account";');
  });

  it('writes drop and add with --no-rename', async () => {
    await setupV1();
    expect(await cmdSchemaDiff(io, { name: 'alterUser', schema: 'db/schema2.ts', renames: [], noRename: true })).toBe(0);
    const sql = read('db/migrations/0002_alter_user.sql');
    expect(sql).toContain('-- WARNING:');
    expect(sql).toContain('DROP COLUMN "name"');
    expect(sql).toContain('ADD COLUMN "fullName"');
  });

  it('keeps the answer no when the user says no', async () => {
    await setupV1();
    io.isTTY = true;
    answer = false;
    await cmdSchemaDiff(io, { name: 'alterUser', schema: 'db/schema2.ts', renames: [], noRename: false });
    expect(read('db/migrations/0002_alter_user.sql')).not.toContain('RENAME COLUMN');
  });

  it('asks about a table rename first, then about columns', async () => {
    writeSchema('name');
    await cmdSchemaDiff(io, { name: 'createUser', renames: [], noRename: false });
    writeFileSync(
      join(cwd, 'db/schema2.ts'),
      schemaSource('fullName').replace("defineTable('User'", "defineTable('Account'"),
    );
    io.isTTY = true;
    expect(await cmdSchemaDiff(io, { name: 'renameUser', schema: 'db/schema2.ts', renames: [], noRename: false })).toBe(0);
    expect(asked).toEqual([
      'Is table "Account" a rename of "User"? (y/N)',
      'Is column "Account"."fullName" a rename of "Account"."name"? (y/N)',
    ]);
    const sql = read('db/migrations/0002_rename_user.sql');
    expect(sql).toContain('ALTER TABLE "User" RENAME TO "Account";');
    expect(sql).toContain('ALTER TABLE "Account" RENAME COLUMN "name" TO "fullName";');
  });

  it('refuses a d1-kyt snapshot', async () => {
    writeSchema('email');
    writeFileSync(join(cwd, 'db/schema.json'), JSON.stringify({ version: 1, tables: { users: { name: 'users', columns: {} } } }));
    expect(await cmdSchemaDiff(io, { renames: [], noRename: false })).toBe(1);
    expect(errors.join('\n')).toContain('schema.json is not a kyt-pg snapshot');
    expect(existsSync(join(cwd, 'db/migrations'))).toBe(false);
  });

  it('reports an up to date schema', async () => {
    writeSchema('email');
    await cmdSchemaDiff(io, { renames: [], noRename: false });
    expect(await cmdSchemaDiff(io, { renames: [], noRename: false })).toBe(0);
    expect(logs.join('\n')).toContain('Schema is up to date.');
    expect(readdirSync(join(cwd, 'db/migrations'))).toHaveLength(1);
  });

  it('parses rename flags', () => {
    expect(parseRenameFlag('User=Account')).toEqual({ kind: 'table', from: 'User', to: 'Account' });
    expect(parseRenameFlag('User.name=fullName')).toEqual({ kind: 'column', table: 'User', from: 'name', to: 'fullName' });
    expect(() => parseRenameFlag('nope')).toThrow('--rename takes');
  });
});
